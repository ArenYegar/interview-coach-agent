def build(existing: list[dict] | None = None) -> list[dict]:
    """把草稿池解析成题库格式（qid 在每个前缀的现有最大编号之后续号）。"""
    import collections
    existing = existing or []
    next_no = collections.Counter()
    for q in existing:
        p, _, n = q["qid"].partition("-")
        try:
            next_no[p] = max(next_no[p], int(n))
        except ValueError:
            pass
    out = []
    for line in DRAFTS.strip().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split("|")
        if len(parts) != 6:
            raise ValueError("字段数不对（应为 6）：" + line[:60])
        prefix, diff, skills, text = parts[0], parts[1], parts[2], parts[3]
        dims = []
        for d in parts[4:]:
            name, criteria, kws = d.split("::")
            dims.append({"name": name.strip(), "weight": 1.0 if not dims else 0.6,
                         "criteria": criteria.strip(),
                         "keywords": [k.strip() for k in kws.split(",") if k.strip()]})
        next_no[prefix] += 1
        out.append({"qid": "%s-%02d" % (prefix, next_no[prefix]),
                    "category": PREFIX_CATEGORY[prefix], "difficulty": diff,
                    "skills": [s.strip() for s in skills.split(",") if s.strip()],
                    "text": text.strip(), "rubric": dims})
    return out
